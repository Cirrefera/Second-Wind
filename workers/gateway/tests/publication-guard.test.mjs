import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createFixtureDb,insertItem} from './helpers/d1.mjs';
import {prepareRelease} from '../../../products/agent-state-dynamodb-manifest/scripts/package.mjs';
import {canonicalJson,sha256} from '../src/contracts.js';
const migration=readFileSync(new URL('../migrations/0006_publication_guard.sql',import.meta.url),'utf8');
test('publication requires exact operator approval; existing live releases and retirement remain usable',async t=>{
 const db=createFixtureDb();t.after(()=>db.close());
 const legacy=insertItem(db);
 db.sqlite.exec(migration);db.sqlite.exec(migration);
 assert.equal(db.sqlite.prepare('SELECT status FROM items WHERE sku=?').get(legacy.sku).status,'live');
 db.sqlite.prepare("UPDATE items SET updated_at='2026-10-19' WHERE sku=?").run(legacy.sku);
 assert.throws(()=>db.sqlite.prepare("UPDATE items SET summary='new promise' WHERE sku=?").run(legacy.sku),/publication_review_required/);
 assert.throws(()=>insertItem(db,{sku:'UNREVIEWED',slug:'unreviewed'}),/publication_requires_staged_product/);
 const {release,routing}=await prepareRelease();
 const item=insertItem(db,{sku:release.sku,slug:release.slug,status:'draft',kind:'artifact',service:'dynamodb',version:release.version,price_usd:0.5});
 const manifestHash=await sha256(canonicalJson(release)),routingHash=await sha256(canonicalJson(routing));
 const approve=db.sqlite.prepare('INSERT INTO release_approvals VALUES (?,?,?,?,?,?,?,?,?,?,?)');
 const catalog=JSON.stringify(db.sqlite.prepare('SELECT * FROM items WHERE sku=?').get(item.sku));
 const values=[item.sku,item.version,manifestHash,routingHash,release.storage.content_hash,catalog,'a'.repeat(64),'test-only-reviewed-evidence','b'.repeat(40),'test-operator','2026-10-19T00:00:00Z'];
 assert.throws(()=>db.sqlite.prepare("UPDATE items SET status='live' WHERE sku=?").run(item.sku),/publication_review_required/);
 assert.throws(()=>approve.run(...values),/reviewed_stored_release_required/);
 db.sqlite.prepare('INSERT INTO component_releases VALUES (?,?,?,?)').run(item.sku,item.version,canonicalJson(release),manifestHash);
 db.sqlite.prepare('INSERT INTO product_routing_manifests VALUES (?,?,?,?,?,?)').run(item.sku,item.version,canonicalJson(routing),routingHash,'test-operator',values.at(-1));
 assert.throws(()=>approve.run(...values),/reviewed_stored_release_required/);
 const s=release.storage;
 db.sqlite.prepare('INSERT INTO payload_objects (id,sku,r2_bucket,r2_key,content_hash,size_bytes,mime_type,version) VALUES (?,?,?,?,?,?,?,?)')
  .run('test-payload',item.sku,s.r2_bucket,s.r2_key,s.content_hash,s.size_bytes,s.mime_type,item.version);
 assert.throws(()=>approve.run(...values.map((v,i)=>i===4?'c'.repeat(64):v)),/reviewed_stored_release_required/);
 assert.throws(()=>approve.run(...values.map((v,i)=>i===5?JSON.stringify({...JSON.parse(catalog),price_usd:0.25}):v)),/reviewed_stored_release_required/);
 approve.run(...values);
 db.sqlite.prepare("UPDATE items SET status='live' WHERE sku=?").run(item.sku);
 for(const sql of ["UPDATE items SET sku='RENAMED'", "UPDATE items SET price_usd=0.4", "UPDATE items SET input_schema='{}'", "UPDATE items SET version=3", "UPDATE items SET guidance='changed'", "UPDATE items SET name='New promise'"])
  assert.throws(()=>db.sqlite.prepare(sql+' WHERE sku=?').run(item.sku),/publication_review_required/);
 assert.throws(()=>db.sqlite.exec("UPDATE payload_objects SET r2_key='changed'"),/approved_payload_immutable/);
 assert.throws(()=>db.sqlite.exec('DELETE FROM payload_objects'),/approved_payload_immutable/);
 assert.throws(()=>db.sqlite.exec('DELETE FROM release_approvals'),/release_approval_immutable/);
 assert.throws(()=>db.sqlite.exec("UPDATE release_approvals SET reviewed_by='changed'"),/release_approval_immutable/);
 db.sqlite.prepare("UPDATE items SET status='retired' WHERE sku=?").run(item.sku);
 assert.equal(db.sqlite.prepare('SELECT status FROM items WHERE sku=?').get(item.sku).status,'retired');
 assert.equal(db.sqlite.prepare('SELECT COUNT(*) n FROM release_approvals').get().n,1);
 const event=db.sqlite.prepare("SELECT payload FROM business_event_outbox WHERE event_type='release.published'").get();
 assert.equal(JSON.parse(event.payload).release_hash,manifestHash);
 assert.equal(JSON.parse(event.payload).exact_amount_atomic,'500000');
});
